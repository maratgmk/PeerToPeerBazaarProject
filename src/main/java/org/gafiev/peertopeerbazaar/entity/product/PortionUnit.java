package org.gafiev.peertopeerbazaar.entity.product;

/**
 * Represents the unit of measurement for a product portion.
 */
public enum PortionUnit {

    /** Weight measurement in kilograms. */
    KILOGRAM,

    /** Volume measurement in liters. */
    LITER,

    /** A single individual item or unit. */
    PIECE,

    /** A group of similar items fastened or growing together (e.g., flowers or herbs). */
    BUNCH,

    /** A collection of matched or related items sold as a single unit. */
    SET
}
